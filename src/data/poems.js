export const getTodayPoem = () => {
  const dayOfYear = Math.floor(
    (new Date() - new Date(new Date().getFullYear(), 0, 0)) / (1000 * 60 * 60 * 24)
  );
  return poems[dayOfYear % poems.length];
};

export const getRecentPoems = (count = 3) => {
  const today = getTodayPoem();
  return poems.filter((p) => p.id !== today.id).slice(0, count);
};
